UNITS = ["", "один", "два", "три", "четыре", "пять",
         "шесть", "семь", "восемь", "девять"]
TEENS = ["десять", "одиннадцать", "двенадцать", "тринадцать",
         "четырнадцать", "пятнадцать", "шестнадцать",
         "семнадцать", "восемнадцать", "девятнадцать"]
TENS = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят",
        "шестьдесят", "семьдесят", "восемьдесят", "девяносто"]
HUNDREDS = ["", "сто", "двести", "триста", "четыреста",
            "пятьсот", "шестьсот", "семьсот", "восемьсот", "девятьсот"]


def number_to_words(n):
    if not isinstance(n, int):
        raise ValueError("Число должно быть целым")
    if n < 1 or n > 1000:
        raise ValueError("Число должно быть от 1 до 1000")
    if n == 1000:
        return "тысяча"

    parts = []
    h = n // 100
    t = (n % 100) // 10
    u = n % 10

    if h:
        parts.append(HUNDREDS[h])
    if t == 1:
        parts.append(TEENS[u])
    else:
        if t:
            parts.append(TENS[t])
        if u:
            parts.append(UNITS[u])

    return " ".join(parts).capitalize()